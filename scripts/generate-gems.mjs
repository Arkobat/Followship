// Turns scripts/fellows-gems.json (gem traits, from scrape-worn.js) into src/data/gemTraitsData.ts: each gem
// colour's ten traits and the gem power they unlock at. Icons are `public/icons/gem-trait-<id>.webp` (96px).
// Usage: node scripts/generate-gems.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)
const data = JSON.parse(readFileSync(new URL('scripts/fellows-gems.json', root), 'utf8'))
const COLOURS = ['ruby', 'amethyst', 'topaz', 'emerald', 'sapphire', 'diamond']

const text = (h) =>
  (h || '')
    .replace(/<br\s*\/?>/g, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/[ \t]+/g, ' ')
    .replace(/ *\n */g, '\n')
    .trim()

const unknown = data.traits.filter((t) => !COLOURS.includes(t.colour)).map((t) => t.colour)
if (unknown.length) {
  console.error(`Unknown gem colours: ${[...new Set(unknown)].join(', ')}`)
  process.exit(1)
}

const traits = data.traits.map((t) => {
  const icon = `icons/gem-trait-${t.id}.webp`
  return {
    colour: t.colour,
    power: t.power,
    name: t.name,
    icon: existsSync(new URL(`public/${icon}`, root)) ? icon : undefined,
    description: text(t.description),
  }
})

writeFileSync(
  new URL('src/data/gemTraitsData.ts', root),
  `// Generated by scripts/generate-gems.mjs from fellows.gg — don't edit by hand.
import type { GemTrait } from './gemPower'

export const GEM_TRAITS: GemTrait[] = ${JSON.stringify(traits, null, 2).replace(/"([a-zA-Z]+)":/g, '$1:')}
`,
)
console.log(`Wrote ${traits.length} gem traits (${traits.filter((t) => t.icon).length} with icons).`)
